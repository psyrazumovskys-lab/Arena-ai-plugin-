/* Языковая и этическая вычитка тетради «После. Возвращение к себе».
   Запуск:  node therapy-workbooks/tests/test_recovery_workbook_language.js

   Проверяет текст так, как его увидит человек:
   1) нет сленга и клинического жаргона без объяснения;
   2) нет формулировок, которые подразумевают только женщину;
   3) на месте бережные формулировки (там, где раньше были оценочные);
   4) сохранены рамка безопасности, телефоны и оговорка про «он» / «она».
   Файл полезен как страж языка для будущих тетрадей: список запрещённого
   можно скопировать и дополнить. */
'use strict';
const fs=require('fs');
const path=require('path');

const file=path.resolve(__dirname,'../recovery_after_destructive_relationships.html');
const html=fs.readFileSync(file,'utf8');
const body=html.slice(html.indexOf('</style>'), html.indexOf('<script>'));
const text=body
  .replace(/<[^>]+>/g,' ')
  .replace(/&nbsp;/g,' ')
  .replace(/&laquo;|&raquo;|&quot;|&mdash;|&ndash;/g,' ')
  .replace(/\s+/g,' ')
  .trim();

const pass=[], fail=[];
const t=(name,cond)=>{ (cond?pass:fail).push(name); };
const has=re=>re.test(text);
const count=re=>(text.match(re)||[]).length;

/* ── 1. сленг и жаргон без объяснения ───────────────────────── */
const JARGON={
  'газлайтинг':/газлайт/i,
  'абьюз':/абьюз/i,
  'токсичные отношения':/токсичн/i,
  'триггер':/триггер/i,
  'флешбэк':/флешбэ|флэшбэ/i,
  'амбивалентность':/амбивалент/i,
  'To-Done':/To-Done/,
  '«бомба любви»':/бомб[аы] любви/i,
  'срыв':/\bсрыв/i,
  'качели':/качел/i,
  'на взводе':/на взводе/i,
  'провалы':/провал(ы|ов)\b/i,
  'виктим / жертва как ярлык':/виктим|жертв(а|ы) (в|насил)/i,
  'клинический жаргон':/дефузи|парентифик|рескрипт|психообразован|копинг|детонатор/i,
};
Object.keys(JARGON).forEach(k=>t('нет жаргона: '+k, !JARGON[k].test(text)));

/* ── 2. род читателя ────────────────────────────────────────── */
const FEMININE={
  'я перестала':/\bя перестала\b/,
  'я придумала':/\bя придумала\b/,
  'я начала':/\bя начала\b/,
  'я стала':/\bя стала\b/,
  'я ждала':/\bя ждала\b/,
  'я жила':/\bя жила\b/,
  'я была':/\bя была\b/,
  'я привыкла':/\bя привыкла\b/,
  'я держалась':/\bя держалась\b/,
  'я замолчала':/\bя замолчала\b/,
  'я ушла':/\bя ушла\b/,
  'я могла':/\bя могла\b/,
  'я терпела':/\bя терпела\b/,
  'я боялась':/\bя боялась\b/,
  'я чувствовала':/\bя чувствовала\b/,
  'я написала':/\bя написала\b/,
  'я надеялась':/\bя надеялась\b/,
  'я виновата':/\bя виновата\b/,
  'сама виновата':/сама виновата/,
  'истеричка':/истеричк/,
  'причёсанной':/причёсанной/,
};
Object.keys(FEMININE).forEach(k=>t('нейтральный род: '+k, !FEMININE[k].test(text)));
t('нейтральные формы «(а)» используются — и не редко', count(/\(а\)|\(ась\)|\(-ась\)|\(-ая\)|\(а\)сь/g)>=20);
t('есть прямая оговорка про «он» / «она»', has(/партнёр везде назван «он»/) && has(/читайте «она»/));
t('оговорка покрывает близких, а не только партнёра', /родители, взрослые дети или другой близкий человек/.test(text));

/* ── 3. бережные формулировки ───────────────────────────────── */
const GENTLE=[
  [/* вместо «на сегодня тетрадь закрыта… не справилась» */ /на сегодня достаточно/,'остановка подана без обвинения'],
  [/это не провал и не слабость/,'прямое снятие самообвинения'],
  [/старайтесь не ругать себя за это/,'мягкая форма вместо «нельзя»'],
  [/Стыд не помогает/,'объяснение вместо укрёпа'],
  [/не ваша ошибка/,'слово о мыслях о смерти — без оценки'],
  [/Так работает привязанность, когда тепло приходит непредсказуемо/,'объяснение тяги без «у всех так»'],
  [/Именно поэтому так трудно отпустить/,'механизм тяги — без аналогии с азартной игрой'],
  [/показной/,'забота: «показная» вместо «имитация»'],
  [/понять, а не осудить себя/,'заголовок о причинах — без самообвинения'],
  [/опора для себя, а не список обид/,'список сцен подан бережно'],
  [/человеку, которому доверяете/,'вместо «живому человеку»'],
  [/право решать самому\(-ой\)/,'фраза о паузе — не про контроль'],
];
GENTLE.forEach(([re,name])=>t('бережная формулировка: '+name, re.test(text)));
const ROUGH=[
  [/живому человеку|живых человек/,'«живой человек» — разговорный оборот'],
  [/как я могла это допустить/,'самообвинение без нейтрализации'],
  [/Тайна — самое сильное топливо/,'метафора «топливо»'],
  [/Вы остаётесь одна\b/,'только женский род'],
  [/это не значит, что вы «должны немедленно уйти»/,'казённое «должны»'],
];
ROUGH.forEach(([re,name])=>t('нет грубой формулировки: '+name, !re.test(text)));

/* ── 4. безопасность и телефоны на месте ───────────────────── */
t('стоп-протокол: три шага', has(/Стоп-протокол/) && has(/Заземление «5-4-3-2-1»/) && has(/Позвоните человеку, которому доверяете/));
t('телефоны: Австрия', has(/0800 222 555/) && has(/0800 246 247/) && has(/133/));
t('телефоны: Россия', has(/8-800-7000-600/) && has(/112/));
t('телефоны детей', has(/8-800-2000-122/) && has(/147/));
t('оговорка про другую страну', has(/найдите местную линию помощи/));
t('предупреждение о специалисте при мыслях о смерти', has(/мысли о том, чтобы не жить/) && has(/идут к специалисту сейчас/));
t('риск признан прямо, без давления на уход', has(/Самые серьёзные пункты — про угрозы/) && has(/решения нужно принимать со специалистом/));
t('никакой диагностики партнёра', !has(/нарцисс|психопат|шизоид/) );
t('нет обещаний результата', !has(/гарантиру|навсегда избавит|вылечит за/));

/* ── отчёт ─────────────────────────────────────────────────── */
console.log('ПРОЙДЕНО: '+pass.length); pass.forEach(x=>console.log('  ✓ '+x));
if(fail.length){ console.log('ПРОВАЛЕНО: '+fail.length); fail.forEach(x=>console.log('  ✗ '+x)); }
console.log('\nОбъём видимого текста: '+text.length+' символов.');
process.exit(fail.length?1:0);
