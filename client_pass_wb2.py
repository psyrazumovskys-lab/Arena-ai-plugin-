def main() -> int:
    html = SRC.read_text(encoding="utf-8")
    applied, skipped = 0, 0
    for name, old, new in EDITS:
        if old not in html:
            print(f"  · пропущено (уже так): {name}")
            skipped += 1
            continue
        html = html.replace(old, new, 1)
        applied += 1
    SRC.write_text(html, encoding="utf-8")
    print(f"Применено {applied}, пропущено {skipped}")
    return 0


