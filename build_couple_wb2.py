def build_pages():
    out = []
    for i, p in enumerate(PAGES):
        prev_id = PAGES[i - 1]["id"] if i > 0 else None
        next_id = PAGES[i + 1]["id"] if i + 1 < len(PAGES) else None

        if p.get("kind") == "cover":
            items = "".join(
                f'<div class="cover-item"><span class="cover-dot"></span><span>{x}</span></div>'
                for x in p["cover_list"])
            body = f'''
    <div class="cover-art"><img class="cover-image" src="__IMG{p["art"]}__" alt="{p["art_alt"]}"></div>
    <div class="cover-body">
      <span class="badge-label terracotta">{p["badge"]}</span>
      <h1 class="cover-title">{p["title"]}</h1>
      <p class="cover-lead">{p["lead"]}</p>
      <div class="cover-list">{items}</div>
      <a class="btn-cover-start" href="#{next_id}" onclick="goToPage('{next_id}'); return false;">Начать</a>
      <div class="cover-meta">{p["meta"]}</div>
    </div>'''
            out.append(f'<div class="page-card cover-card active" id="{p["id"]}">{body}\n  </div>')
            continue

        parts = []
        if p.get("art") is not None:
            parts.append(hero(p["art"], p["art_alt"]))
        badge_class = " " + p["badge_class"] if p.get("badge_class") else ""
        parts.append(f'<span class="badge-label{badge_class}">{p["badge"]}</span>')
        parts.append(f'<h1>{p["title"]}</h1>')
        parts.append(p["body"])
        if p.get("entry"):
            e = p["entry"]
            parts.append(entry(e["field"], e["kind"], e["hint"], e["ph"], e["heading"]))

        nav = []
        if prev_id:
            label = "‹ Назад"
            nav.append(f'<a class="btn-nav-step" href="#{prev_id}" onclick="goToPage(\'{prev_id}\'); return false;">{label}</a>')
        else:
            nav.append('<span></span>')
        if next_id:
            nxt = PAGES[i + 1]
            short = nxt["nav"]
            nav.append(f'<a class="btn-nav-step primary" href="#{next_id}" '
                       f'onclick="goToPage(\'{next_id}\'); return false;">{short} ›</a>')
        else:
            nav.append('<a class="btn-nav-step primary" href="#p0" onclick="goToPage(\'p0\'); return false;">В начало тетради ›</a>')
        parts.append('    <div class="page-footer-nav">' + "".join(nav) + '</div>')

        out.append(f'<div class="page-card" id="{p["id"]}">\n    ' + "\n    ".join(parts) + '\n  </div>')
    return "\n\n  ".join(out)


