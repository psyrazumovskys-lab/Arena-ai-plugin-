SCRIPT = '''
  // Записи в дневниковых блоках второй тетради
  const ENTRIES_PREFIX = 'wb_couples_l2_entries_';

  function readEntries(fieldId) {
    try { return JSON.parse(localStorage.getItem(ENTRIES_PREFIX + fieldId)) || []; }
    catch (e) { return []; }
  }

  function writeEntries(fieldId, arr) {
    try { localStorage.setItem(ENTRIES_PREFIX + fieldId, JSON.stringify(arr)); } catch (e) {}
  }

  function appendEntryItem(list, text, animate) {
    const empty = list.querySelector('.entry-empty');
    if (empty) empty.remove();
    const item = document.createElement('div');
    item.className = animate ? 'entry-item is-new' : 'entry-item';
    item.textContent = text;
    list.appendChild(item);
    if (animate) setTimeout(() => item.classList.remove('is-new'), 300);
  }

  function renderEntries(fieldId) {
    const list = document.getElementById('list_' + fieldId);
    if (!list) return;
    const arr = readEntries(fieldId);
    if (!arr.length) return;
    arr.forEach(text => appendEntryItem(list, text, false));
  }

  function saveEntry(fieldId) {
    const textarea = document.getElementById(fieldId);
    const list = document.getElementById('list_' + fieldId);
    if (!textarea || !list) return;
    const text = textarea.value.trim();
    if (!text) return;
    appendEntryItem(list, text, true);
    const arr = readEntries(fieldId);
    arr.push(text);
    writeEntries(fieldId, arr);
    textarea.value = '';
    saveData(fieldId, '');
    triggerSaveIndicator();
  }

  // Навигация по страницам
  const pages = __PAGES__;
  let currentPageIndex = 0;

  function updateView() {
    pages.forEach((pId, idx) => {
      const el = document.getElementById(pId);
      if (el) el.classList.toggle('active', idx === currentPageIndex);
    });
    const sel = document.getElementById('pageSelect');
    if (sel) sel.value = pages[currentPageIndex];
    document.body.classList.toggle('on-cover', currentPageIndex === 0);
    const prevBtn = document.getElementById('prevBtn');
    const nextBtn = document.getElementById('nextBtn');
    if (prevBtn) prevBtn.disabled = (currentPageIndex === 0);
    if (nextBtn) nextBtn.disabled = (currentPageIndex === pages.length - 1);
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }

  function goToPage(pId) {
    const idx = pages.indexOf(pId);
    if (idx !== -1) { currentPageIndex = idx; updateView(); }
  }

  function stepPage(delta) {
    const nextIdx = currentPageIndex + delta;
    if (nextIdx >= 0 && nextIdx < pages.length) { currentPageIndex = nextIdx; updateView(); }
  }

  // Черновики: то, что набрано, но ещё не сохранено записью
  const inputIds = [__FIELDS__];

  function saveData(key, val) {
    try { localStorage.setItem('wb_couples_l2_' + key, val); } catch (e) {}
  }

  function triggerSaveIndicator() {
    const ind = document.getElementById('saveIndicator');
    if (ind) {
      ind.classList.add('show');
      setTimeout(() => ind.classList.remove('show'), 1500);
    }
  }

  window.addEventListener('DOMContentLoaded', () => {
    inputIds.forEach(id => {
      const el = document.getElementById(id);
      if (el) {
        let saved = null;
        try { saved = localStorage.getItem('wb_couples_l2_' + id); } catch (e) {}
        if (saved) el.value = saved;
        el.addEventListener('input', () => saveData(id, el.value));
      }
      renderEntries(id);
    });
    updateView();
  });

  window.addEventListener('hashchange', () => {
    const id = location.hash.replace('#', '');
    if (pages.indexOf(id) !== -1) goToPage(id);
  });
'''


